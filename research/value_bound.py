"""Оптимистическая верхняя граница для ЛЮБЫХ перестановочных связей (дубликат, AoS↔SoA, переупорядочивание записей,
изменение шага): доля нетривиальных 64-битных слов, значение которых встречается в памяти ещё раз.
Плюс расширение целых: нетривиальные uint64 < 2^32, равные какому-либо uint32 в другом месте.
Граница сверху: повтор значения не гарантирует связь буферов (например, один указатель хранится во многих объектах)."""
import sys, numpy as np
raw = np.fromfile(sys.argv[1], dtype=np.uint64)
nt = raw[(raw > 65535) & (raw != np.uint64(2**64 - 1))]
u, c = np.unique(nt, return_counts=True)
extra = int((c - 1).sum())
pairs = int(((c == 2)).sum())  # значения ровно с двумя копиями — типично для копии буфера
print(f"Нетривиальных слов: {100*nt.size/raw.size:.1f}% памяти")
print(f"  слов-повторов (граница для перестановочных связей): {100*extra/raw.size:.1f}% памяти")
print(f"  из них в парах «ровно 2 копии» (похоже на копию буфера): {100*pairs/raw.size:.1f}% памяти")
small64 = u[u < 2**32]
# uint32 только из слов, где обе половины «настоящие» (массив uint32), иначе uint64 < 2^32 совпадёт сам с собой
packed = raw[raw >= np.uint64(2**32)].view(np.uint32).reshape(-1, 2)
packed = packed[(packed > 65535).all(axis=1)].ravel()
u32 = np.unique(packed)
w = np.isin(small64, u32)
cnt_w = int(c[u < 2**32][w].sum())
print(f"  uint64, совпадающие с каким-то uint32 (граница для расширения): {100*cnt_w/raw.size:.1f}% памяти")
